import { DuckDBInstance, type DuckDBConnection } from '@duckdb/node-api';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export function readDefinitionsSQL(directory = join(__dirname, '..', 'sql')): string {
  return ['result.sql', ...readdirSync(join(directory, 'metrics')).filter((name) => name.endsWith('.sql'))
    .sort().map((name) => join('metrics', name))]
    .map((file) => readFileSync(join(directory, file), 'utf8'))
    .join('\n');
}

export async function generateProfilingSQL(definitionsSQL: string): Promise<string> {
  const instance = await DuckDBInstance.create(':memory:', { threads: '1' });
  let connection: DuckDBConnection | undefined;
  try {
    connection = await instance.connect();
    await connection.run(definitionsSQL);
    const reader = await connection.runAndReadAll(`
      SELECT function_name, function_type, parameters FROM duckdb_functions()
      WHERE (starts_with(function_name, 'data_profiling_')
        OR starts_with(function_name, '_data_profiling_parameters_'))
        AND function_name NOT IN ('data_profiling_value', 'data_profiling_result')
      ORDER BY function_name
    `);
    const functions = reader.getRowObjectsJson() as {
      function_name: string; function_type: string; parameters: string[];
    }[];
    const metrics = functions.filter(({ function_name }) => function_name.startsWith('data_profiling_'));
    const parameterHelpers = new Set(functions.filter(({ function_name }) =>
      function_name.startsWith('_data_profiling_parameters_')).map(({ function_name }) => function_name));
    if (!metrics.length) throw new Error('No data_profiling_* metric macros found');

    // Keep one aggregate row even when only metadata metrics exist and the input is empty.
    const aggregates = ['count(*) AS __profile_rows'];
    // shortcut: aggregate and metadata metrics only; extend for pairs or extra stages.
    const results = metrics.map(({ function_name: name, function_type: type, parameters }, index) => {
      if (type !== 'macro' || !/^data_profiling_[a-z][a-z0-9_]*$/.test(name)) {
        throw new Error(`Unsupported metric macro: ${name}`);
      }
      const metric = name.slice('data_profiling_'.length);
      let columns = '[]::VARCHAR[]';
      let value: string;
      if (!parameters.length) {
        value = `metric_${index}`;
        aggregates.push(`${name}() AS ${value}`);
      } else if (parameters.length === 1 && parameters[0] === 'table_name') {
        value = `${name}(table_name)`;
      } else if (parameters.length === 1 && parameters[0] === 'column_value') {
        const prefix = `metric_${index}_`;
        aggregates.push(`${name}(COLUMNS(*)) AS "${prefix}\\0"`);
        value = `COLUMNS('^${prefix}')`;
        columns = `[substr(alias(${value}), ${prefix.length + 1})]`;
      } else {
        throw new Error(`Unsupported parameters for ${name}: use (), (table_name), or (column_value)`);
      }
      const helper = `_data_profiling_parameters_${metric}`;
      const metricParameters = parameterHelpers.has(helper) ? `${helper}()` : "'{}'::JSON";
      return `data_profiling_result(table_name, ${columns}, '${metric}', ${value}, ${metricParameters}) AS "result_${index}_\\0"`;
    });

    return `-- Generated by npm run build; edit sql/result.sql and sql/metrics/*.sql instead.
${definitionsSQL}
CREATE OR REPLACE MACRO data_profiling(table_name) AS TABLE
SELECT * FROM (
SELECT unnest([*COLUMNS(*)], recursive := true)
FROM (
    SELECT
        ${results.join(',\n        ')}
    FROM (
        SELECT
            ${aggregates.join(',\n            ')}
        FROM query_table(table_name)
    )
)
) WHERE value IS NOT NULL;
`;
  } finally {
    connection?.closeSync();
    instance.closeSync();
  }
}

if (require.main === module) {
  generateProfilingSQL(readDefinitionsSQL())
    .then((sql) => writeFileSync(join(__dirname, 'data_profiling.sql'), sql))
    .catch((error: unknown) => { console.error(error); process.exitCode = 1; });
}
